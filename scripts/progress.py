"""Write decomp/PROGRESS.md from decomp/functions.csv.

A function counts as *named* once its Ghidra name is no longer the default FUN_xxxxxxxx.
Run after every export:  python -I scripts/progress.py
"""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / "decomp" / "functions.csv", encoding="utf-8")))


def named(r):
    return not r["name"].startswith(("FUN_", "thunk_FUN_"))


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "-"


total = len(rows)
size = sum(int(r["size"], 16) for r in rows)
ok = sum(r["status"] == "decompiled" for r in rows)
nm = [r for r in rows if named(r)]
nm_size = sum(int(r["size"], 16) for r in nm)

per_file = defaultdict(lambda: [0, 0, 0])
for r in rows:
    s = per_file[r["file"]]
    s[0] += 1
    s[1] += named(r)
    s[2] += int(r["size"], 16)

out = [
    "# Progress",
    "",
    "Generated by `scripts/progress.py` from `decomp/functions.csv`.",
    "",
    "| Measure | Count | Share |",
    "|---|---|---|",
    f"| Functions found | {total} | |",
    f"| Decompiled by Ghidra | {ok} | {pct(ok, total)} |",
    f"| Named (not `FUN_`) | {len(nm)} | {pct(len(nm), total)} |",
    f"| Code bytes in named functions | {nm_size} of {size} | {pct(nm_size, size)} |",
    f"| Matching (byte-identical) | 0 | 0.0% |",
    "",
    "## Per file",
    "",
    "| File | Functions | Named | Code bytes |",
    "|---|---|---|---|",
]
for f in sorted(per_file):
    n, k, b = per_file[f]
    out.append(f"| [{f}]({f}) | {n} | {k} ({pct(k, n)}) | {b} |")
(ROOT / "decomp" / "PROGRESS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{total} functions, {len(nm)} named, {ok} decompiled")
