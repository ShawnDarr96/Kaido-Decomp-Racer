"""Measure how much of .text is covered by functions, using the exact body ranges the export
writes to decomp/function_ranges.csv. Writes decomp/COVERAGE.md.

    python -I scripts/coverage.py

Regions that are not EE code are listed in config/vu_microcode.txt (VU1 microcode) and below
(the kernel-patch syscall tables); they are excluded from the EE code count.
"""
import csv
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ELF = ROOT / "iso_extract" / "SLES_531.91"
TEXT = (0x100000, 0x308080)
NOT_EE = [(0x2FD9B8, 0x306D50, "VU1 microcode (config/vu_microcode.txt)"),
          (0x306EB0, 0x307218, "kernel-patch syscall table: {number, kernel address} pairs"),
          (0x307999, 0x307A04, "kernel-patch syscall table (second part)")]


def main():
    d = ELF.read_bytes()
    w = lambda v: struct.unpack_from("<I", d, v - 0x100000 + 0x80)[0]
    ranges = sorted((int(r["start"], 16), int(r["end"], 16))
                    for r in csv.DictReader(open(ROOT / "decomp/function_ranges.csv")))
    nfuncs = len({r["address"] for r in csv.DictReader(open(ROOT / "decomp/function_ranges.csv"))})
    size = TEXT[1] - TEXT[0]
    cov = bytearray(size)
    for a, b in ranges:
        a, b = max(a, TEXT[0]), min(b, TEXT[1])
        if a < b:
            cov[a - TEXT[0]:b - TEXT[0]] = b"\1" * (b - a)
    in_not_ee = lambda x: any(s <= x < e for s, e, _ in NOT_EE)
    not_ee = sum(e - s for s, e, _ in NOT_EE)
    covered = sum(cov)
    left = [x for x in range(*TEXT, 4) if not cov[x - TEXT[0]] and not in_not_ee(x) and w(x)]
    runs, cur = [], [left[0]] if left else []
    for x in left[1:]:
        if x - cur[-1] <= 8:
            cur.append(x)
        else:
            runs.append(cur)
            cur = [x]
    if cur:
        runs.append(cur)
    ee = size - not_ee
    lines = ["# .text coverage", "",
             "Generated by `scripts/coverage.py` from the exact function body ranges in "
             "`decomp/function_ranges.csv`.", "",
             f"- functions: {nfuncs}",
             f"- .text: 0x{TEXT[0]:x}-0x{TEXT[1]:x} ({size} bytes); not EE code: {not_ee} bytes",
             f"- EE bytes inside function bodies: {covered} ({100 * covered / ee:.2f}% of the EE code bytes)",
             f"- EE bytes outside function bodies: {ee - covered}, of which zero padding: "
             f"{ee - covered - 4 * len(left)}",
             f"- non-zero EE words outside every function: {len(left)} in {len(runs)} runs "
             f"({sum(1 for r in runs if len(r) == 1)} single words)", "",
             "## Not EE code", ""]
    lines += [f"- 0x{s:08x}-0x{e:08x}: {why}" for s, e, why in NOT_EE]
    lines += ["", "## Largest uncovered runs", "",
              "Mostly exception landing code inside the C++ runtime (calls `__throw`, runs in the "
              "caller's frame) and single unreachable instructions.", "",
              "| start | words | first words |", "|---|---|---|"]
    for r in sorted(runs, key=len, reverse=True)[:25]:
        lines.append(f"| 0x{r[0]:08x} | {len(r)} | {' '.join('%08x' % w(r[0] + 4 * k) for k in range(min(4, len(r))))} |")
    (ROOT / "decomp" / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[4:9]))


if __name__ == "__main__":
    main()
